def icon(name):
    """The whole <svg> for one icon, sized and colored by the CSS around it."""
    return (
        '<svg class="icon" viewBox="0 0 24 24" fill="none" stroke="currentColor"'
        ' stroke-width="2" stroke-linecap="round" stroke-linejoin="round"'
        ' aria-hidden="true">%s</svg>' % ICONS[name]
    )


def with_icons(page):
    """Replace every @ICON:name@ in a template. An unknown name raises, so a
    typo shows up the moment the module is imported, not as a hole in the page."""
    return re.sub(r"@ICON:([a-z0-9-]+)@", lambda m: icon(m.group(1)), page)
